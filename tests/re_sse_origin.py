"""Where do the SSE event names actually live?

Our server.py parses these SSE event names off the wire:
    progress_notice, prompt, metadata, output, token_usage, done, error
but 'progress_notice' was NOT found in ai_agent.dll. That matters: if those
names are not in the client binary either, then they are produced by the
SERVER (api/ide/v1/chat), not by the local sidecar - which would mean the SSE
contract is a remote API contract, and our parser is already talking to the
right layer.

Check both DLLs and the JS bundles for each event name.
"""
from __future__ import annotations

import io
import os
import sys

TRAE = r"D:\Users\marcus\AppData\Local\Programs\Trae CN"
FILES = [
    (os.path.join(TRAE, r"resources\app\modules\ai-agent\ai_agent.dll"),
     "ai_agent.dll"),
    (os.path.join(TRAE, r"resources\app\modules\ai-agent\harness.dll"),
     "harness.dll"),
    (os.path.join(TRAE, r"resources\app\out\vs\workbench"
                 r"\workbench.desktop.main.js"), "workbench.js"),
    (os.path.join(TRAE, r"resources\app\out\main.js"), "main.js"),
]
NEEDLES = [
    "progress_notice", "token_usage", "finish_reason", "reasoning_content",
    "prompt_completion_id", "tool_calls", "prompt_cache_pool_record",
    "construct_prompt", "ide_prompts", "text/event-stream",
]

OUT: list[str] = []


def log(*a):
    OUT.append(" ".join(str(x) for x in a))


def main() -> int:
    log(f"{'needle':30} " + " ".join(f"{n:>14}" for _, n in FILES))
    log("-" * 92)
    bufs = {}
    for path, label in FILES:
        if not os.path.exists(path):
            log(f"!! missing {label}")
            continue
        with io.open(path, "rb") as f:
            bufs[label] = f.read()

    for needle in NEEDLES:
        row = f"{needle:30} "
        for _, label in FILES:
            b = bufs.get(label)
            row += f"{b.count(needle.encode()) if b else 0:>14} "
        log(row)

    log("\n=== interpretation ===")
    for needle in ("progress_notice", "construct_prompt", "ide_prompts"):
        in_client = any(
            (bufs.get(l) or b"").count(needle.encode()) > 0
            for _, l in FILES)
        log(f"  {needle:20} present in local client binaries: {in_client}")
    log("\n  If progress_notice/ide_prompts are ABSENT locally but DO appear")
    log("  in live SSE responses, they are generated by the remote server,")
    log("  i.e. our parser already targets the correct (server) contract.")

    io.open(os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))), "logs", "_sse_origin.txt"), "w",
        encoding="utf-8").write("\n".join(OUT))
    print("\n".join(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
